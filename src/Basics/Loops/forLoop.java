package Basics.Loops;

public class forLoop {
    public static void main(String[] args){
        // order of the numbers
        for (int i =1;i<=10;i++){
            System.out.println(i);
        }
        System.out.println("===================");
        // reverse the numbers
        for (int j = 10; j >0; j--){
            System.out.println(j);
        }
    }
}
