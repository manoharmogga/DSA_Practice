package Basics;

public class Literals {
    public static void main(String [] args){
        //literals
        int i = 123;
        double d = 9.99999999D;
        float f = 12.367F;
        long l = 90_32_234_2389L;

        System.out.println(i);
        System.out.println(d);
        System.out.println(f);
        System.out.println(l);
    }
}
